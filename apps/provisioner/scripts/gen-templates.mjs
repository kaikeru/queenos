// Build-time generator (runs under Node, never bundled into the Worker).
// Workers cannot read repo files at runtime, so embed templates/<name>/** as
// a TS module: { "<name>": { "<path>": "<utf-8 content>" } }.
// Output is deterministic (sorted paths) and only rewritten when it changes.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../../templates");
const out = resolve(here, "../src/templates.generated.ts");
const NAMES = ["worker-starter"];

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir).sort()) {
    const p = join(dir, entry);
    if (statSync(p).isDirectory()) files.push(...walk(p));
    else files.push(p);
  }
  return files;
}

const templates = {};
for (const name of NAMES) {
  const base = join(root, name);
  const files = {};
  for (const p of walk(base)) {
    const rel = relative(base, p).split("\\").join("/");
    if (rel === ".DS_Store" || rel.endsWith("/.DS_Store")) continue;
    files[rel] = readFileSync(p, "utf8");
  }
  templates[name] = Object.fromEntries(Object.entries(files).sort(([a], [b]) => (a < b ? -1 : 1)));
}

const body = `// GENERATED by scripts/gen-templates.mjs from /templates. Do not edit by hand.
/* eslint-disable */
export const TEMPLATES: Record<string, Record<string, string>> = ${JSON.stringify(templates, null, 2)};
`;

if (!existsSync(out) || readFileSync(out, "utf8") !== body) writeFileSync(out, body);
