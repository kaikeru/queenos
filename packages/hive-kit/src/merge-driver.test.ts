import { describe, expect, it } from "vitest";
import { diff3MergeText, isRegistrySource, mergeRegistryContents, registryMergeDriver } from "./merge-driver.js";
import { REGISTRY_HEADER, renderRegistry } from "./registry.js";

const BR = ["base", "main", "member"];
const merge = (base: string, ours: string, theirs: string) => diff3MergeText({ branches: BR, contents: [base, ours, theirs] });

describe("mergeRegistryContents", () => {
  it("unions additions from both sides", () => {
    const base = renderRegistry(["a.js"]);
    expect(mergeRegistryContents(base, renderRegistry(["a.js", "b.js"]), renderRegistry(["a.js", "c.js"]))).toBe(renderRegistry(["a.js", "b.js", "c.js"]));
  });

  it("keeps removals from either side", () => {
    const base = renderRegistry(["a.js", "b.js"]);
    expect(mergeRegistryContents(base, renderRegistry(["b.js", "c.js"]), renderRegistry(["a.js", "b.js", "d.js"]))).toBe(renderRegistry(["b.js", "c.js", "d.js"]));
  });

  it("handles an empty base (add/add)", () => {
    expect(mergeRegistryContents("", renderRegistry(["x.js"]), renderRegistry(["y.js"]))).toBe(renderRegistry(["x.js", "y.js"]));
  });
});

describe("isRegistrySource", () => {
  it("accepts generated registries, the empty template and empty text", () => {
    expect(isRegistrySource(renderRegistry(["a.js", "b.js"]))).toBe(true);
    expect(isRegistrySource("// GENERATED by the QueenOS builder drone. Do not edit by hand.\nexport const features = [];\n")).toBe(true);
    expect(isRegistrySource("")).toBe(true);
    // The header is any `//` line: a hive created with the old header still merges, and so does the new one.
    expect(isRegistrySource(`${REGISTRY_HEADER}\nexport const features = [];\n`)).toBe(true);
  });

  it("rejects anything with code a module-set merge would drop", () => {
    expect(isRegistrySource('import * as f0 from "./a.js";\nexport const features = [f0];\nconsole.log("x");\n')).toBe(false);
    expect(isRegistrySource('export default function index() {}\n')).toBe(false);
  });
});

describe("registryMergeDriver", () => {
  it("merges the registry by module set (isomorphic-git passes the basename)", async () => {
    const base = renderRegistry([]);
    const r = await registryMergeDriver({ branches: BR, contents: [base, renderRegistry(["a.js"]), renderRegistry(["b.js"])], path: "index.js" });
    expect(r).toEqual({ cleanMerge: true, mergedText: renderRegistry(["a.js", "b.js"]) });
  });

  it("falls back to diff3 for a hand-written index.js and for other paths", async () => {
    const r = await registryMergeDriver({ branches: BR, contents: ["x\n", "y\n", "z\n"], path: "index.js" });
    expect(r.cleanMerge).toBe(false);
    const ok = await registryMergeDriver({ branches: BR, contents: ["1\n2\n3\n", "1x\n2\n3\n", "1\n2\n3x\n"], path: "theme.js" });
    expect(ok).toEqual({ cleanMerge: true, mergedText: "1x\n2\n3x\n" });
  });
});

describe("diff3MergeText (isomorphic-git's default driver)", () => {
  it("merges non-overlapping edits", () => {
    expect(merge("a\nb\nc\nd\n", "A\nb\nc\nd\n", "a\nb\nc\nD\n")).toEqual({ cleanMerge: true, mergedText: "A\nb\nc\nD\n" });
  });

  it("takes identical edits once", () => {
    expect(merge("a\nb\n", "a\nB\n", "a\nB\n")).toEqual({ cleanMerge: true, mergedText: "a\nB\n" });
  });

  it("keeps insertions from both sides at different places", () => {
    expect(merge("a\nb\nc\n", "a\nx\nb\nc\n", "a\nb\nc\ny\n")).toEqual({ cleanMerge: true, mergedText: "a\nx\nb\nc\ny\n" });
  });

  it("marks overlapping edits as a conflict with git-style markers", () => {
    const r = merge("a\nb\nc\n", "a\nB1\nc\n", "a\nB2\nc\n");
    expect(r.cleanMerge).toBe(false);
    expect(r.mergedText).toBe("a\n<<<<<<< main\nB1\n=======\nB2\n>>>>>>> member\nc\n");
  });

  it("handles deletions and an empty base", () => {
    expect(merge("a\nb\nc\n", "a\nc\n", "a\nb\nc\n")).toEqual({ cleanMerge: true, mergedText: "a\nc\n" });
    expect(merge("", "same\n", "same\n").cleanMerge).toBe(true);
    expect(merge("", "one\n", "two\n").cleanMerge).toBe(false);
  });
});
